"""Generate the independent effect consumer's typed syntax edges."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]


def generate():
	model = json.loads((ROOT/'compiler/syntax/model.json').read_text())['nodes']
	lines = ['// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception', 'language astra27b;', '// Generated by generate-effects.py. Handler semantics live in effect-source.astra.', 'void checked_effect_source_children(CheckedIndex index, CheckedEffectSource source, SyntaxNodeId node, int depth) {', '\tmatch (index.bindings.program.arena.kind(node)) {']
	for name, record in model.items():
		if record['abstract']: continue
		lines.append('\t\tcase SyntaxKind.'+name+'(): {')
		for field, typ in record['fields'].items():
			if field in ('foreign_member', 'foreign_channels'): continue
			# Callable bodies are visited with their own bound, never with the
			# ambient callable's error/handler/catch context.
			if name in ('ClassDeclarationSyntax', 'StructDeclarationSyntax', 'EnumDeclarationSyntax', 'FunctionDeclarationSyntax', 'LifecycleDeclarationSyntax', 'TryStatementSyntax', 'LambdaExpressionSyntax'): continue
			if field in ('vector', 'subscript') and name == 'VectorExtractExpressionSyntax': continue
			if typ.rstrip('?') in model:
				lines.append('\t\t\tchecked_effect_source_visit(index, source, index.bindings.program.arena.get_node_'+field+'(node), depth);')
			elif re.fullmatch(r'GenericArray<\w+Syntax>\??', typ):
				lines += ['\t\t\tvar list_'+field+' = index.bindings.program.arena.get_list_'+field+'(node);', '\t\t\tforeach (var at_'+field+' in 0..index.bindings.program.arena.list_count(list_'+field+')) {', '\t\t\t\tchecked_effect_source_visit(index, source, index.bindings.program.arena.node_at(list_'+field+', at_'+field+'), depth);', '\t\t\t}']
		lines.append('\t\t}')
	lines += ['\t\telse: { assert_that(false); }', '\t}', '}']
	return '\n'.join(lines)+'\n'


if __name__ == '__main__':
	p = argparse.ArgumentParser(); p.add_argument('--check', action='store_true'); a = p.parse_args()
	path = ROOT/'compiler/semantic/effect-walk.astra'; data = generate()
	if a.check: assert path.read_text() == data, 'stale effect traversal'
	else: path.write_text(data)
