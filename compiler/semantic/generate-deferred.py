"""Generate only typed traversal of explicitly deferred syntax subtrees."""
import argparse
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[2]


def generate():
	model=json.loads((ROOT/'compiler/syntax/model.json').read_text())['nodes']
	lines=['// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception', '// Generated by generate-deferred.py; no type decisions in this traversal.', 'void checked_deferred_children(CheckedIndex index, SyntaxNodeId node, int reason, int depth) throws Error {', '\tif (node.index == 0 || index.failed()) { return; }', '\tif (depth > 256) { index.fail(index.uses[node.index].span, "deferred syntax depth exceeds 256"); return; }', '\tmatch (index.bindings.program.arena.kind(node)) {']
	for name,record in model.items():
		if record['abstract']: continue
		lines.append('\t\tcase SyntaxKind.'+name+'(): {')
		for field,typ in record['fields'].items():
			if field in ('foreign_member','foreign_channels'): continue
			if field in ('methods','members') and name in ('ClassDeclarationSyntax','StructDeclarationSyntax'): continue
			if field in ('vector', 'subscript') and name=='VectorExtractExpressionSyntax': continue
			if field in ('second','destination') and name=='DspExpressionSyntax': pass
			if typ.rstrip('?') in model:
				lines.append('\t\t\tchecked_deferred_node(index, index.bindings.program.arena.get_node_'+field+'(node), reason, depth + 1);')
			elif re.fullmatch(r'GenericArray<\w+Syntax>\??',typ):
				lines += ['\t\t\tvar list_'+field+' = index.bindings.program.arena.get_list_'+field+'(node);', '\t\t\tint at_'+field+' = 0;', '\t\t\twhile (at_'+field+' < index.bindings.program.arena.list_count(list_'+field+')) {', '\t\t\t\tchecked_deferred_node(index, index.bindings.program.arena.node_at(list_'+field+', at_'+field+'), reason, depth + 1);', '\t\t\t\tat_'+field+' = at_'+field+' + 1;', '\t\t\t}']
		lines.append('\t\t}')
	lines += ['\t\telse: { assert_that(false); }', '\t}', '}', 'void checked_deferred_node(CheckedIndex index, SyntaxNodeId node, int reason, int depth) throws Error {', '\tif (node.index == 0 || index.failed() || index.uses[node.index].deferred != 0) { return; }', '\tvar ignored = index.defer(node, reason);', '\tchecked_deferred_children(index, node, reason, depth + 1);', '}']
	return '\n'.join(lines)+'\n'


if __name__=='__main__':
	p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
	path=ROOT/'compiler/semantic/deferred-walk.astra';data=generate()
	if a.check: assert path.read_text()==data, 'stale deferred traversal'
	else: path.write_text(data)
