"""Generate typed child scheduling only; binding decisions remain in index.astra."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
model = json.loads((ROOT / 'compiler/syntax/model.json').read_text())['nodes']
lines = ['// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception', '// Generated by generate-walk.py from the syntax schema; no text scanning.', 'void schedule_children(SyntaxNodeId node, ScopeId scope) throws Error {', '\tmatch (this.program.arena.kind(node)) {']
# These are duplicate metadata views or non-language metadata, not extra uses.
skip = {'foreign_member', 'foreign_channels', 'type_applications', 'methods', 'fields', 'factory_syntax', 'foreign_import', 'foreign_export', 'com_export', 'gobject_export', 'ccode', 'floating_point', 'allocator', 'alignment', 'representation', 'foreign_policy', 'policy'}
for name, spec in model.items():
	if spec['abstract']:
		continue
	lines.append(f'\t\tcase SyntaxKind.{name}(): {{')
	fields = list(spec['fields'].items())
	if name == 'CompilationUnitSyntax':
		fields = [(k, spec['fields'][k]) for k in ('c_classes', 'com_interfaces', 'structs', 'classes', 'enums', 'constants', 'functions', 'async_runtimes')]
	if name == 'ForStatementSyntax':
		fields = [(k, spec['fields'][k]) for k in ('initializer', 'condition', 'body', 'step')]
	if name == 'VectorExtractExpressionSyntax':
		fields = [(k, v) for k, v in fields if k not in ('container', 'subscript')]
	for field, typ in reversed(fields):
		if field in skip and not (field == 'fields' and name in ('EnumVariantSyntax', 'StructInitializerSyntax')):
			continue
		if name == 'BufferAllocationSyntax' and field == 'count':
			lines.append('\t\t\tthis.schedule_count(node, scope);')
		elif typ.rstrip('?') in model:
			lines.append(f'\t\t\tthis.push(this.program.arena.get_node_{field}(node), scope, 0);')
		elif typ.startswith('GenericArray<') and typ[13:].rstrip('>?') in model:
			lines.append(f'\t\t\tthis.push_list(this.program.arena.get_list_{field}(node), scope);')
	lines.append('\t\t}')
lines += ['\t\telse: {', '\t\t\tassert_that(false);', '\t\t}', '\t}', '}']
p = ROOT / 'compiler/semantic/index.astra'
s = p.read_text()
a = s.index('\t// BEGIN GENERATED CHILD SCHEDULING')
b = s.index('\t// END GENERATED CHILD SCHEDULING', a)
expected = s[:a] + '\t// BEGIN GENERATED CHILD SCHEDULING\n' + ''.join('\t' + line + '\n' for line in lines) + s[b:]
if '--check' in sys.argv:
	if expected != s: raise SystemExit('generated child scheduler drift; regenerate then use tools/format/source.py')
else:
	p.write_text(expected)
