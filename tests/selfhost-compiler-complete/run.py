"""Observe every tracked compiler source; a refusal never counts as admission."""
import argparse
import ast
import hashlib
import json
import os
from pathlib import Path
import signal
import subprocess
import time

ROOT = Path(__file__).resolve().parents[2]
WORK = ROOT.parent/'codex/work/astra'
BASE = '8b8cf003ea0b47b1322b887317b6fc535bfb9850'
C0_SHA256 = 'e3b2a5d6a4b9c5a42becbc3704f2d062489fb6f99a5ed1727461dfef4cf8681b'


def sha(path):
	with Path(path).open('rb') as stream:
		return hashlib.file_digest(stream, 'sha256').hexdigest()


def git(*args):
	return subprocess.check_output(['git', '-C', str(ROOT), *args])


def write(path, value):
	path.write_text(json.dumps(value, indent=2)+'\n')


def declarations(text):
	depth = 0
	quoted = escaped = False
	first = None
	result = []
	for i, char in enumerate(text):
		if quoted:
			if escaped:
				escaped = False
			elif char == '\\':
				escaped = True
			elif char == '"':
				quoted = False
		elif char == '"':
			quoted = True
		elif char == '(':
			depth += 1
			if depth == 2:
				first = i
		elif char == ')':
			assert depth > 0
			if depth == 2:
				value = text[first:i+1].encode()
				result.append(dict(kind=value[1:].split(None, 1)[0].decode().rstrip(')'), AST_bytes=len(value), AST_sha256=hashlib.sha256(value).hexdigest()))
			depth -= 1
	assert depth == 0 and not quoted
	return result


def population():
	files = git('ls-files', '-z', 'compiler', 'lib/astra').decode().split('\0')
	compiler = sorted(name for name in files if name.startswith('compiler/') and name.endswith('.astra'))
	recipe = ROOT/'tests/selfhost-typecore/build.py'
	model = ast.parse(recipe.read_text())
	libraries = next(ast.literal_eval(node.value) for node in model.body if isinstance(node, ast.Assign) and any(isinstance(target, ast.Name) and target.id == 'LIBRARIES' for target in node.targets))
	libraries = ['lib/astra/'+name+'.astra' for name in libraries]
	assert compiler and len(libraries) == len(set(libraries)) and all(name in files for name in libraries)
	baseline = git('ls-tree', '-r', '--name-only', BASE, 'compiler').decode().splitlines()
	assert {name for name in baseline if name.endswith('.astra')} <= set(compiler)
	rows = []
	for name in [*compiler, *libraries]:
		path = ROOT/name
		assert path.is_file() and not path.is_symlink()
		blob = git('rev-parse', BASE+':'+name).decode().strip()
		original = git('cat-file', 'blob', blob)
		lineage = [line for line in path.read_text().splitlines()[:6] if 'Generated' in line or 'generated by' in line.lower()]
		rows.append(dict(path=name, bytes=path.stat().st_size, sha256=sha(path), baseline_blob=blob, baseline_sha256=hashlib.sha256(original).hexdigest(), included_because='entire tracked compiler population' if name in compiler else 'explicit current compiler library dependency', generated_lineage_comments=lineage))
	outside = sorted(name for name in files if name.endswith('.astra') and name not in compiler and name not in libraries)
	return dict(format='astra-compiler-source-population/1', baseline_commit=BASE, HEAD=git('rev-parse', 'HEAD').decode().strip(), compiler_files=len(compiler), library_files=len(libraries), files=rows, library_authority=dict(path=str(recipe.relative_to(ROOT)), sha256=sha(recipe)), other_libraries=[dict(path=name, sha256=sha(ROOT/name), disposition='not a dependency in the current compiler build recipe; not counted as translated') for name in outside], entrypoint='No production main exists under compiler/. The prior test observer is a separate compiler host, not target input.', limitation='Whole compiler source inclusion is exact. Dependency edges and complete semantic admission require separate evidence; a library exclusion is not a compiler-source exclusion.')


def diagnostic(data, paths):
	for line in data.splitlines():
		row = line.split()
		if len(row) == 5 and row[0] in ('ERROR', 'CHECKED_ERROR'):
			path = Path(bytes.fromhex(row[1]).decode())
			assert path in paths
			first, last = int(row[2]), int(row[3])
			raw = path.read_bytes()
			assert 0 <= first <= last <= len(raw)
			return dict(stage='Typecore', path=paths[path], input_path=str(path), first=first, last=last, line=raw[:first].count(b'\n')+1, fragment_sha256=hashlib.sha256(raw[first:last]).hexdigest(), message=bytes.fromhex(row[4]).decode())
	return None


def ledger(path, inputs, output):
	sources = {str(p):p.read_bytes() for p in inputs}
	count = 0
	decls = 0
	with path.open() as stream, output.open('w') as nodes:
		for line in stream:
			row = line.split()
			if not row:
				continue
			if row[0] == 'SOURCE' and len(row) >= 2:
				name = bytes.fromhex(row[1]).decode()
				backing = bytes(int(value) for value in row[2:])
				if name not in sources:
					sources[name] = backing
				else:
					assert sources[name] == backing
			elif row[0] == 'DECL':
				decls += 1
			elif row[0] == 'NODE':
				assert len(row) == 10
				name = bytes.fromhex(row[7]).decode()
				assert name in sources
				raw = sources[name]
				first, last = int(row[8]), int(row[9])
				assert 0 <= first <= last <= len(raw)
				count += 1
				assert int(row[1]) == count
				value = dict(node=count, syntax_kind=int(row[2]), function_symbol=int(row[3]), type=int(row[4]), flags=int(row[5]), deferred=int(row[6]), path=name, first=first, last=last, fragment_sha256=hashlib.sha256(raw[first:last]).hexdigest(), disposition='recorded type is not whole-program acceptance' if int(row[4]) else 'unvisited or structural; not admitted')
				nodes.write(json.dumps(value, separators=(',', ':'))+'\n')
	return dict(nodes=count, declarations=decls, raw_ledger_sha256=sha(path), node_index_sha256=sha(output), synthetic_sources=[dict(path=name, bytes=len(data), sha256=hashlib.sha256(data).hexdigest()) for name, data in sources.items() if Path(name) not in inputs])


def main():
	p = argparse.ArgumentParser(description=__doc__)
	p.add_argument('--compiler', type=Path, required=True)
	p.add_argument('--component', action='append', required=True, help='O0=/absolute/product or O2=/absolute/product')
	p.add_argument('--build', type=Path, required=True)
	p.add_argument('--runtime', type=Path, required=True)
	p.add_argument('--check-timeout', type=int, default=900)
	p.add_argument('--skip-check', action='store_true', help='Explicitly leave C0 semantic validity unproved')
	a = p.parse_args()
	assert sha(a.compiler) == C0_SHA256
	assert subprocess.check_output(['llvm-config', '--version']).strip() == b'23.1.4'
	for path, parent in ((a.build, WORK/'build'), (a.runtime, WORK/'runtime')):
		assert path.is_absolute() and path.resolve().is_relative_to(parent.resolve()) and not path.resolve().is_relative_to(ROOT)
		assert all(not entry.is_symlink() for entry in (path, *path.parents))
		path.mkdir(parents=True, exist_ok=True)
	stamp = str(time.time_ns())
	build = a.build/stamp
	runtime = a.runtime/stamp
	build.mkdir()
	runtime.mkdir()
	plan = population()
	# Original compiler sources are target data, distinct from the current host
	# implementation. Preserve exact baseline bytes even for files being fixed.
	inputs = []
	logical_paths = {}
	for row in plan['files']:
		target = runtime/'original-inputs'/row['path']
		target.parent.mkdir(parents=True, exist_ok=True)
		target.write_bytes(git('cat-file', 'blob', row['baseline_blob']))
		target.chmod(0o444)
		assert sha(target) == row['baseline_sha256']
		row['input_path'] = str(target)
		inputs.append(target)
		logical_paths[target] = row['path']
	commands = []
	def run(argv, name, timeout=300):
		argv = list(map(str, argv))
		start = time.monotonic()
		with (runtime/(name+'.stdout')).open('wb') as out, (runtime/(name+'.stderr')).open('wb') as err:
			process = subprocess.Popen(['/usr/bin/time', '-v', '-o', str(runtime/(name+'.time')), *argv], cwd=build, stdout=out, stderr=err, start_new_session=True, env=dict(os.environ, CCACHE_DISABLE='1'))
			timed_out = False
			try:
				code = process.wait(timeout)
			except subprocess.TimeoutExpired:
				timed_out = True
				os.killpg(process.pid, signal.SIGKILL)
				code = process.wait()
		row = dict(name=name, argv=argv, exit=code, timed_out=timed_out, seconds=time.monotonic()-start, stdout_sha256=sha(runtime/(name+'.stdout')), stderr_sha256=sha(runtime/(name+'.stderr')))
		commands.append(row)
		print(name, code, 'timeout' if timed_out else 'completed', flush=True)
		return row
		# Syntax parsing is independent of target optimization. Keep exact raw ASTs.
	for n, row in enumerate(plan['files']):
		name = 'syntax-'+str(n)
		observed = run([a.compiler, '--dump-syntax', row['input_path']], name)
		assert observed['exit'] == 0 and not observed['timed_out']
		row['C0_syntax'] = dict(receipt=name, raw_AST_sha256=observed['stdout_sha256'], declarations=declarations((runtime/(name+'.stdout')).read_text()))
	check = None if a.skip_check else run([a.compiler, '--check', *inputs], 'C0-complete-check', a.check_timeout)
	profiles = {}
	for value in a.component:
		mode, filename = value.split('=', 1)
		assert mode in ('O0', 'O2') and mode not in profiles
		component = Path(filename)
		identity = json.loads(component.with_suffix('.identity.json').read_text())
		assert sha(component) == identity['sha256'] and identity['identity']['argv'][:2] == [str(a.compiler), '-'+mode]
		for group in ('sources', 'tools'):
			assert all(sha(path) == expected for path, expected in identity['identity'][group].items())
		target = build/(mode+'.ll')
		sentinel = b'Whole compiler output refusal sentinel\n'
		target.write_bytes(sentinel)
		native = run([component, '--native', target, *inputs], mode+'-native')
		boundary = diagnostic((runtime/(mode+'-native.stdout')).read_text(), logical_paths)
		result = dict(component=str(component), component_sha256=sha(component), identity_sha256=sha(component.with_suffix('.identity.json')), native=native, first_frontier=boundary, full_source_emitted=False, LLVM_verified=False, object_generated=False, linkage_verified=False, runtime_verified=False)
		if native['exit'] != 0:
			assert target.read_bytes() == sentinel
			result['refusal_destination_preserved'] = True
		else:
			assert not native['timed_out'] and target.read_bytes() != sentinel
			result['full_source_emitted'] = True
			verified = run(['opt', '-passes=verify', '-disable-output', target], mode+'-verify')
			result['LLVM_verified'] = verified['exit'] == 0
			if result['LLVM_verified']:
				obj = build/(mode+'.o')
				generated = run(['llc', '-filetype=obj', '-'+mode, target, '-o', obj], mode+'-object')
				result['object_generated'] = generated['exit'] == 0 and obj.is_file()
				if result['object_generated']:
					result['object_sha256'] = sha(obj)
		observed = run([component, '--classstorage-source-ledger', mode, build/'unused', *inputs], mode+'-source-ledger')
		assert not observed['timed_out']
		result['class_storage_ledger'] = ledger(runtime/(mode+'-source-ledger.stdout'), inputs, runtime/(mode+'-nodes.jsonl'))
		if not result['full_source_emitted'] and result['first_frontier'] is None:
			lines = (runtime/(mode+'-native.stdout')).read_text().splitlines()
			for line in lines:
				parts = line.split()
				if len(parts) == 4 and parts[0] == 'RECOVER_FLOW' and int(parts[1]) != 0:
					status, node = int(parts[1]), int(parts[2])
					result['first_frontier'] = dict(stage='Flow', status=status, node=node, source_span=None)
					with (runtime/(mode+'-nodes.jsonl')).open() as stream:
						for raw in stream:
							entry = json.loads(raw)
							if entry['node'] == node:
								entry['original_path'] = logical_paths.get(Path(entry['path']))
								result['first_frontier']['source_span'] = entry
								break
				for marker, stage in (('RECOVER_CORE_INVALID', 'Core'), ('RECOVER_CFG_INVALID', 'CFG'), ('RECOVER_SSA_INVALID', 'SSA')):
					if line == marker:
						result['first_frontier'] = dict(stage=stage, message=marker, source_span=None)
		profiles[mode] = result
	assert all(sha(ROOT/row['path']) == row['sha256'] for row in plan['files'])
	write(runtime/'population.json', plan)
	write(runtime/'commands.json', commands)
	write(runtime/'result.json', dict(status='PARTIAL', population_sha256=sha(runtime/'population.json'), C0_check=check, profiles=profiles, limitation='Full-source observations only. Class-storage ledger and effects-native admission are separate profiles. No successful process, syntax parse, count or reduced witness qualifies whole compiler completeness; integrated ABI/link/runtime/memory/performance and later gates remain unproved.'))
	print('PARTIAL', runtime/'result.json', flush=True)


if __name__ == '__main__':
	main()
